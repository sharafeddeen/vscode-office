import {test} from 'node:test';
import assert from 'node:assert/strict';
import {join} from 'node:path';
import {promises as fs} from 'node:fs';
import {createHash} from 'node:crypto';
import ExcelJS from '@cweijan/exceljs';
import JSZip from 'jszip';
import {fixture,nativeFixture} from './fixture';
import {UnoDocument} from '../../src/spreadsheet/uno';
import {loadSheets} from '../../src/react/view/excel/excel_reader';
import {readResults} from '../../src/spreadsheet/results';

test('UNO keeps native workbook metadata, edits, undo/redo, arrays and export',{skip:!process.env.RUN_UNO},async()=>{
    const source=await nativeFixture(),hash=createHash('sha256').update(source).digest('hex');
    const grid=(await loadSheets(source.buffer as ArrayBuffer,'.xlsx')).sheets;
    const doc=await UnoDocument.open(source,'xlsx',{workerPath:join(process.cwd(),'src/spreadsheet/uno-worker.py'),timeoutMs:90000});
    const root=doc.root;
    try {
        await doc.bind(grid);
        assert.equal((await doc.request('inspect')).macroMode,0);
        assert.ok((await doc.request('inspect')).names.includes('Efficiency'));
        grid[1].rows![0].cells[0].text='0.9';delete grid[1].rows![0].cells[0].savedValue;grid[1].rows![0].cells[0].hasSavedValue=false;
        const sync=await doc.sync(grid);assert.equal(sync.changed,true);
        assert.equal((await doc.snapshot()).results.QUICK_SPLITS.J2.value,100);
        await doc.operation({action:'undo'});
        assert.equal((await doc.snapshot()).results.QUICK_SPLITS.J2.value,90);
        const afterUndo=(await loadSheets((await doc.export()).buffer as ArrayBuffer,'.xlsx')).sheets;
        await doc.bind(afterUndo);await doc.sync(afterUndo);
        await doc.operation({action:'redo'});
        const result=await doc.snapshot();
        assert.equal(result.results.QUICK_SPLITS.J2.value,100);
        assert.equal(result.results.QUICK_SPLITS.L2.value,1);assert.equal(result.results.QUICK_SPLITS.L3.value,2);assert.equal(result.results.QUICK_SPLITS.L4.value,3);
        assert.equal(result.results.QUICK_SPLITS.N2.value,0);assert.equal(result.results.QUICK_SPLITS.N3.value,false);assert.equal(result.results.QUICK_SPLITS.N4.value,'');
        const exported=await doc.export('xlsx'),zip=await JSZip.loadAsync(exported);
        assert.match(await zip.file('xl/workbook.xml')!.async('string'),/name="Efficiency"/);
        assert.match(await zip.file('xl/worksheets/sheet1.xml')!.async('string'),/conditionalFormatting/);
        assert.equal(createHash('sha256').update(source).digest('hex'),hash);
        const current=(await loadSheets((await doc.export()).buffer as ArrayBuffer,'.xlsx')).sheets;
        await doc.bind(current);
        const row=current[0].rows![2] ??= {cells:{}};
        (row as any).cells[9]={text:'=IF(Efficiency>0,90/Efficiency,0)',formulaPreview:true,previewCell:true};
        current[0].styles ??= [];
        const style=current[0].styles.length;
        current[0].styles.push({font:{name:'Arial',size:14,bold:true,italic:true},color:'#112233',bgcolor:'#ffeecc',align:'right',valign:'middle',textwrap:true,underline:true,strike:true,border:{bottom:['thin','#123456']},format:'percent'});
        (row as any).cells[9].style=style;
        (row as any).cells[14]={text:'2024-02-01',previewCell:true};
        (row as any).cells[15]={text:'00123',previewCell:true,style:style+1};
        current[0].styles.push({format:'text'});
        await doc.sync(current);
        assert.equal((await doc.snapshot()).results.QUICK_SPLITS.J3.value,100);
        const formatted=(await loadSheets((await doc.export()).buffer as ArrayBuffer,'.xlsx')).sheets[0];
        const formattedCell=formatted.rows![2].cells[9];
        assert.ok(formatted.styles![formattedCell.style!].font?.bold);
        assert.equal(formatted.styles![formattedCell.style!].format,'percent');
        assert.equal(formatted.rows![2].cells[15].text,'00123');
        assert.ok(formatted.rows![2].cells[14].numFmt?.match(/[dmy]/i));
        await doc.operation({action:'insertRows',sheet:1,index:0,count:1});
        assert.equal((await doc.snapshot()).results.QUICK_SPLITS.J2.value,100,'Native names follow row insertion');
        await doc.operation({action:'insertColumns',sheet:1,index:0,count:1});
        assert.equal((await doc.snapshot()).results.QUICK_SPLITS.J2.value,100);
        await doc.operation({action:'deleteColumns',sheet:1,index:0,count:1});
        await doc.operation({action:'addSheet',name:'Temporary',index:3});
        await doc.operation({action:'renameSheet',sheet:3,name:'Renamed'});
        await doc.operation({action:'duplicateSheet',sheet:3,name:'Copy',index:4});
        await doc.operation({action:'moveSheet',sheet:4,index:3});
        assert.deepEqual((await doc.request('inspect')).sheets.slice(3),['Copy','Renamed']);
        await doc.operation({action:'deleteSheet',sheet:4});
        await doc.operation({action:'deleteSheet',sheet:3});
        const fresh=(await loadSheets((await doc.export()).buffer as ArrayBuffer,'.xlsx')).sheets;
        await doc.bind(fresh);
        const rejected=structuredClone(fresh);rejected[0].images=[{id:'test'} as any];
        await assert.rejects(doc.sync(rejected),/Editing images is not connected/);
        assert.equal((await doc.snapshot()).results.QUICK_SPLITS.J2.value,100);
        const saved=await doc.export();
        const reopened=await UnoDocument.open(saved,'xlsx',{workerPath:join(process.cwd(),'src/spreadsheet/uno-worker.py')});
        try{assert.ok((await reopened.request('inspect')).names.includes('Efficiency'));assert.equal((await readResults(await reopened.export())).QUICK_SPLITS.J2.value,100);}
        finally{await reopened.dispose();}
    }finally{await doc.dispose();}
    await assert.rejects(fs.stat(root));
});
